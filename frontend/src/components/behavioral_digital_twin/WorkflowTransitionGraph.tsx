import React, { useMemo } from "react";
import { GitFork } from "lucide-react";
import {
  ReactFlow,
  Controls,
  Background,
  Node,
  Edge,
  MarkerType,
} from "@xyflow/react";
import "@xyflow/react/dist/style.css";

interface WorkflowTransitionGraphProps {
  transitionMatrix?: Record<string, Record<string, number>>;
}

export const WorkflowTransitionGraph: React.FC<WorkflowTransitionGraphProps> = ({
  transitionMatrix = {},
}) => {
  const { nodes, edges } = useMemo(() => {
    const rawNodes = new Set<string>();
    const edgeList: Edge[] = [];

    // Collect all unique nodes and build edges
    Object.entries(transitionMatrix).forEach(([fromNode, targets]) => {
      rawNodes.add(fromNode);
      Object.entries(targets || {}).forEach(([toNode, prob]) => {
        rawNodes.add(toNode);
        edgeList.push({
          id: `e-${fromNode}->${toNode}`,
          source: fromNode,
          target: toNode,
          label: `${Math.round(prob * 100)}%`,
          type: "smoothstep",
          animated: prob > 0.5,
          markerEnd: {
            type: MarkerType.ArrowClosed,
            width: 16,
            height: 16,
            color: "#38bdf8",
          },
          style: {
            stroke: prob > 0.5 ? "#38bdf8" : "#64748b",
            strokeWidth: prob > 0.5 ? 2 : 1.2,
          },
          labelStyle: {
            fill: "#38bdf8",
            fontWeight: 700,
            fontSize: "10px",
            fontFamily: "monospace",
          },
          labelBgStyle: {
            fill: "#0b0f17",
            fillOpacity: 0.9,
            stroke: "#1e293b",
          },
        });
      });
    });

    const nodeList = Array.from(rawNodes);

    // Compute simple grid/layer positioning
    const layoutNodes: Node[] = nodeList.map((nodeKey, idx) => {
      const col = idx % 3;
      const row = Math.floor(idx / 3);

      const parts = nodeKey.split(":");
      const method = parts.length > 1 ? parts[0] : "API";
      const path = parts.length > 1 ? parts.slice(1).join(":") : nodeKey;

      const methodColors: Record<string, string> = {
        GET: "#38bdf8",
        POST: "#34d399",
        PUT: "#fbbf24",
        DELETE: "#f43f5e",
      };
      const borderColor = methodColors[method.toUpperCase()] || "#94a3b8";

      return {
        id: nodeKey,
        position: { x: 50 + col * 320, y: 60 + row * 140 },
        data: {
          label: (
            <div className="text-left font-mono space-y-0.5">
              <span
                className="text-[10px] font-bold px-1.5 py-0.2 rounded"
                style={{
                  backgroundColor: `${borderColor}20`,
                  color: borderColor,
                  border: `1px solid ${borderColor}50`,
                }}
              >
                {method}
              </span>
              <div className="text-[11px] font-semibold text-slate-200 truncate max-w-[220px]">
                {path}
              </div>
            </div>
          ),
        },
        style: {
          background: "#0b0f17",
          border: `1px solid ${borderColor}60`,
          borderRadius: "8px",
          padding: "10px 14px",
          color: "#f8fafc",
          boxShadow: "0 4px 12px rgba(0,0,0,0.5)",
          width: 250,
        },
      };
    });

    return { nodes: layoutNodes, edges: edgeList };
  }, [transitionMatrix]);

  if (nodes.length === 0) {
    return (
      <div className="bg-phantom-900 border border-slate-800/80 rounded-lg p-12 text-center space-y-3">
        <GitFork className="w-10 h-10 text-slate-600 mx-auto" />
        <h4 className="text-sm font-semibold text-slate-300 font-mono">No Workflow Sequences Learned</h4>
        <p className="text-xs text-slate-500 max-w-md mx-auto">
          Markov transition sequences are generated by compiling session-ordered observation traces. Once an active baseline with transitions is compiled, the state machine graph will render here.
        </p>
      </div>
    );
  }

  return (
    <div className="bg-phantom-900 border border-slate-800/80 rounded-lg overflow-hidden flex flex-col h-[520px]">
      <div className="p-3 border-b border-slate-800 flex items-center justify-between text-xs font-mono text-slate-400 bg-slate-950/40">
        <div className="flex items-center gap-2">
          <GitFork className="w-4 h-4 text-cyan-400" />
          <span className="font-semibold text-slate-200">Behavioral State Machine</span>
          <span className="text-slate-500">({nodes.length} States, {edges.length} Transitions)</span>
        </div>
        <div className="flex items-center gap-3 text-[11px]">
          <span className="text-slate-500">Edge weights represent transition probability P(next | current)</span>
        </div>
      </div>

      <div className="flex-1 w-full bg-slate-950">
        <ReactFlow
          nodes={nodes}
          edges={edges}
          fitView
          attributionPosition="bottom-right"
          minZoom={0.2}
          maxZoom={1.5}
        >
          <Background color="#1e293b" gap={20} size={1} />
          <Controls className="!bg-slate-900 !border-slate-800 !text-slate-300" />
        </ReactFlow>
      </div>
    </div>
  );
};
